    /// <summary>A song whose missing difficulties Fix selected generates (CHR087), as the Generate difficulties dialog shows it.</summary>
    /// <param name="Title">The song's name, as the Validator lists it.</param>
    /// <param name="Pairs">Its <c>song.ini</c> as drafted.</param>
    /// <param name="Draft">A copy of its draft, which nothing changes, to read off the UI thread; null for none.</param>
    /// <param name="Targets">Each part's missing difficulties, highest first.</param>
    public sealed record GenerateDifficultiesSong(
        SongEntry Entry,
        string Title,
        IReadOnlyList<KeyValuePair<string, string>> Pairs,
        MetadataDraft? Draft,
        IReadOnlyDictionary<ChartInstrument, IReadOnlyList<ChartDifficulty>> Targets)
    {
        /// <summary>The parts Fix selected generates star power for too (CHR066), before the difficulties; none when it doesn't.</summary>
        public IReadOnlyList<ChartInstrument> StarPower { get; init; } = [];

        /// <summary>What generating does to the song's chart: its missing difficulties filled, with any star power first.</summary>
        public SongGenerationWork Work => new(Targets.Count > 0, StarPower);

        /// <summary>Each part's missing difficulties in <paramref name="targets"/>, e.g. "Guitar Hard, Medium; Drums Easy".</summary>
        public static string DescribeTargets(IReadOnlyDictionary<ChartInstrument, IReadOnlyList<ChartDifficulty>> targets) =>
            string.Join(
                Strings.ValidatorMissingPartSeparator,
                targets.Select(t => string.Format(
                    CultureInfo.CurrentCulture,
                    Strings.ValidatorMissingPartFormat,
                    ChartLabels.InstrumentName(t.Key),
                    string.Join(", ", t.Value.Select(ChartLabels.DifficultyName)))));
    }

    /// <summary>The Generate difficulties dialog: the rules the songs' missing difficulties are generated by, with a preview.</summary>
    public interface IGenerateDifficultiesDialog
    {
        /// <summary>Shows <paramref name="songs"/> and the default rules to change.</summary>
        /// <returns>The rules to generate by, or null when it's cancelled.</returns>
        Task<ReductionDefaults?> ShowAsync(IReadOnlyList<GenerateDifficultiesSong> songs);
    }

    /// <summary>Shows the Generate difficulties dialog over the window <paramref name="owner"/> gives.</summary>
    /// <param name="rules">The default rules, which the dialog starts from and can save.</param>
    /// <param name="newPlayer">Makes the dialog a player of its own, for its preview to play the song picked.</param>
    /// <param name="ownerPlayer">The owner's player, stopped while the dialog's can play.</param>
    public sealed class AvaloniaGenerateDifficultiesDialog(Func<Window?> owner, ReductionRulesFile rules, Func<PlayerViewModel> newPlayer, PlayerViewModel? ownerPlayer = null) : IGenerateDifficultiesDialog
    {
        public async Task<ReductionDefaults?> ShowAsync(IReadOnlyList<GenerateDifficultiesSong> songs)
        {
            if (owner() is not { } window || songs.Count == 0)
                return null;

            if (ownerPlayer?.StopCommand.CanExecute(null) == true)
                ownerPlayer.StopCommand.Execute(null);
            var player = newPlayer();
            try
            {
                using var viewModel = new GenerateDifficultiesViewModel(songs, rules, player);
                var dialog = new GenerateDifficultiesWindow { DataContext = viewModel };
                WindowChrome.UseOwnerIcon(dialog, window);
                await dialog.ShowDialog(window);
                return viewModel.Result;
            }
            finally
            {
                // The songs may be written once the dialog's done, so its player lets go of their files first.
                player.Unload();
                await player.WhenFilesClosedAsync();
                player.Dispose();
                ownerPlayer?.ReloadSettings();
            }
        }
    }
}
